export type AdminLocale = 'vi' | 'en'

export function getAdminLocale(value?: string): AdminLocale {
  return value === 'en' ? 'en' : 'vi'
}

export function withAdminLocale(path: string, locale: AdminLocale) {
  return `${path}?lang=${locale}`
}

